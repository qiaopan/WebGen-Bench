#!/usr/bin/env bash
# SessionStart hook: prints live repo/experiment state so a fresh session
# never has to blindly trust docs/agent-memory/HANDOFF.md.
# Must never fail the session: every risky command is guarded.

ROOT="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null)}"
[ -d "$ROOT" ] || exit 0
cd "$ROOT" 2>/dev/null || exit 0

echo "## Live repo state (auto-generated by SessionStart hook, not part of shared memory)"
echo

echo "### git status --short"
git status --short 2>/dev/null | head -40
echo

echo "### git log -5 --oneline"
git log -5 --oneline 2>/dev/null
echo

HANDOFF="docs/agent-memory/HANDOFF.md"
if [ -f "$HANDOFF" ]; then
  NEWER=$(find outputs/experiment -maxdepth 2 -name 'continual-report.json' -newer "$HANDOFF" 2>/dev/null)
  if [ -n "$NEWER" ]; then
    echo "### Warning: experiment outputs newer than HANDOFF.md"
    echo "The following continual-report.json files were modified after docs/agent-memory/HANDOFF.md was last written. HANDOFF.md's operational state may be stale for these runs — verify against the file itself before trusting HANDOFF's description of them."
    echo "$NEWER"
    echo
  fi
else
  echo "### Warning: docs/agent-memory/HANDOFF.md not found"
  echo
fi

exit 0

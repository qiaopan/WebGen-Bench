#!/usr/bin/env bash
# Codex cold-start helper.  It is intentionally read-only and never changes
# shared memory: an agent must make the semantic update decision itself.

set -u

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
[ -d "$ROOT" ] || exit 0
cd "$ROOT" 2>/dev/null || exit 0

echo "## Live repo state (generated by scripts/codex-handoff-brief.sh; not shared memory)"
echo

echo "### git status --short"
git status --short 2>/dev/null | head -40 || true
echo

echo "### git log -5 --oneline"
git log -5 --oneline 2>/dev/null || true
echo

if ! git diff --quiet 2>/dev/null || ! git diff --cached --quiet 2>/dev/null; then
  echo "### git diff --stat (tracked changes)"
  git diff --stat 2>/dev/null | head -30 || true
  git diff --cached --stat 2>/dev/null | head -30 || true
  echo
fi

HANDOFF="docs/agent-memory/HANDOFF.md"
if [ -f "$HANDOFF" ]; then
  NEWER="$(find outputs/experiment -maxdepth 3 \( -name 'continual-report.json' -o -name 'stage1-report.json' \) -newer "$HANDOFF" -print 2>/dev/null | head -40)"
  if [ -n "$NEWER" ]; then
    echo "### Warning: experiment outputs newer than HANDOFF.md"
    echo "These reports are newer than $HANDOFF. Verify their contents before trusting the operational status in HANDOFF.md."
    echo "$NEWER"
    echo
  fi
else
  echo "### Warning: docs/agent-memory/HANDOFF.md not found"
  echo
fi

exit 0
